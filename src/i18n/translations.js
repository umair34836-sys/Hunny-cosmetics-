export function translate(lang, key, vars) {
  const entry = translations[key]
  let str = entry ? entry[lang] || entry.en : key
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v)
    })
  }
  return str
}
